import { initializeApp } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';
import { getStorage } from 'firebase-admin/storage';
import { getAuth } from 'firebase-admin/auth';
import { callable } from './core/callable.js';
import { createSalesHandlers } from './sales/handlers.js';
import { createCashSessionHandlers } from './cash-register/handlers.js';
import { createCashAutoCloser } from './cash-register/scheduled.js';
import { createAuditNotificationHandler } from './audit/events.js';
import { onSchedule } from 'firebase-functions/v2/scheduler';
import { onDocumentCreated, onDocumentWritten } from 'firebase-functions/v2/firestore';
import { createContractHandlers } from './contracts/handlers.js';
import { createLegacyPaymentReader } from './contracts/legacyReader.js';
import { createAdministrationHandlers } from './platform/administration.js';
import { createPlatformJobs } from './platform/jobs.js';
import { observeOperation, logJobState } from './core/observability.js';

initializeApp();
const database = getFirestore();
const sales = createSalesHandlers(database);
export const submitSale = callable(sales.submitSale, 'submitSale');
export const voidSale = callable(sales.voidSale, 'voidSale');
const cash = createCashSessionHandlers(database);
export const saveCashSession = callable(cash.saveCashSession, 'saveCashSession');
export const openCashSession = callable(cash.openCashSession, 'openCashSession');
export const closeCashSession = callable(cash.closeCashSession, 'closeCashSession');
export const forceCloseCashSession = callable(cash.forceCloseCashSession, 'forceCloseCashSession');
export const reserveOfflineCashSession = callable(cash.reserveOfflineCashSession, 'reserveOfflineCashSession');
export const previewCashSessionClose = callable(cash.previewCashSessionClose, 'previewCashSessionClose');
export const reconcileCashSession = callable(cash.reconcileCashSession, 'reconcileCashSession');
export const autoCloseCashSessions = onSchedule({ schedule: 'every 15 minutes', timeZone: 'America/Lima', region: 'us-central1', maxInstances: 1 },
  observeOperation('autoCloseCashSessions', createCashAutoCloser(database)));
export const notifyAuditEvent = onDocumentCreated({ document: 'audit_events/{eventId}', region: 'us-central1', maxInstances: 10, retry: true },
  event => createAuditNotificationHandler(database)(event.params.eventId));
const contracts = createContractHandlers(database);
export const createContract = callable(contracts.createContract, 'createContract');
export const updateContract = callable(contracts.updateContract, 'updateContract');
export const addContractPayment = callable(contracts.addContractPayment, 'addContractPayment');
export const cancelContract = callable(contracts.cancelContract, 'cancelContract');
export const markContractDelivered = callable(contracts.markContractDelivered, 'markContractDelivered');
export const getLegacyContractPayments = callable(createLegacyPaymentReader(database), 'getLegacyContractPayments');
const administration = createAdministrationHandlers(database);
const jobs = createPlatformJobs(database, getStorage().bucket(), getAuth());
export const createTenant = callable(administration.createTenant, 'createTenant');
export const extendTenantLicense = callable(administration.extendTenantLicense, 'extendTenantLicense');
export const setTenantLicenseStatus = callable(administration.setTenantLicenseStatus, 'setTenantLicenseStatus');
export const getTenantAdministration = callable(administration.getTenantAdministration, 'getTenantAdministration');
export const startTenantBackup = callable(administration.startTenantBackup, 'startTenantBackup');
export const requestTenantDeletion = callable(administration.requestTenantDeletion, 'requestTenantDeletion');
export const cancelTenantDeletion = callable(administration.cancelTenantDeletion, 'cancelTenantDeletion');
export const startTenantPurge = callable(administration.startTenantPurge, 'startTenantPurge');
export const getPlatformJob = callable(jobs.getPlatformJob, 'getPlatformJob');
export const retryPlatformJob = callable(jobs.retryPlatformJob, 'retryPlatformJob');
export const startRestoreDryRun = callable(jobs.startRestoreDryRun, 'startRestoreDryRun');
export const getBackupDownload = callable(jobs.getBackupDownload, 'getBackupDownload');
export const cancelPlatformBackup = callable(jobs.cancelPlatformBackup, 'cancelPlatformBackup');
export const processPlatformJob = onDocumentWritten({ document: 'platform_jobs/{jobId}', region: 'us-central1', maxInstances: 5, timeoutSeconds: 120, memory: '512MiB', retry: true }, event => {
  const before = event.data?.before.data(), after = event.data?.after.data();
  logJobState(before, after);
  if (after?.status !== 'queued' || (before?.status === 'queued' && before.unit === after.unit)) return;
  return jobs.runUnit(event.params.jobId);
});
export const resumePlatformJobs = onSchedule({ schedule: 'every 1 minutes', region: 'us-central1', maxInstances: 1, timeoutSeconds: 120 }, observeOperation('resumePlatformJobs', jobs.sweep));
